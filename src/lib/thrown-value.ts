/**
 * Описание БРОШЕННОГО значения, которое само не бросает.
 *
 * ЗАЧЕМ ОТДЕЛЬНЫМ МОДУЛЕМ. Эта логика нужна двум границам сразу: портальной
 * (`poi-portal-place.ts`) и каноническому резолверу (`place-resolve.ts`).
 * Портальная граница импортирует резолвер, поэтому обратный импорт невозможен,
 * а копия рядом была бы хуже цикла: две редакции fail-closed процедуры
 * расходятся молча, и расходятся они ровно на враждебном значении, ради
 * которого написаны. Модуль ничего не импортирует и ни от чего не зависит.
 *
 * Здесь нет ни `instanceof`, ни единого прямого чтения свойства у unknown.
 * Историю каждого запрета см. в комментариях ниже: каждый поставлен по
 * предъявленному исполняемому контрпримеру, а не из осторожности.
 */

/**
 * Потолок длины текста исключения, попадающего в отчёт и очередь разбора.
 * Брошенное значение приходит извне и длины не имеет: провайдер вправе вернуть
 * мегабайт, и он уехал бы в отчёт целиком.
 */
export const RESOLVER_ERROR_TEXT_LIMIT = 200

/**
 * Обрезка НЕСКОЛЬКИХ фрагментов до общего потолка одним ограниченным проходом.
 *
 * Принимает фрагменты, а не готовую строку, намеренно. Прежняя редакция сначала
 * склеивала `имя + ': ' + сообщение` и только потом обрезала: два внешних куска
 * по мегабайту материализовались в третий на два мегабайта — ровно та работа,
 * которую обрезка и должна была отменить. Здесь потолок ОБЩИЙ на все фрагменты:
 * суммарно потребляется не более `limit + 1` кодовой точки, и до второго
 * фрагмента дело часто не доходит вовсе.
 *
 * Итератор строки ленив, поэтому проход обрывается на месте, а не после полного
 * обхода. Идём по КОДОВЫМ ТОЧКАМ, а не по единицам UTF-16: срез посреди
 * суррогатной пары даёт одиночный суррогат, который при кодировании в UTF-8
 * превращается в U+FFFD — то есть два разных текста стали бы одним.
 */
export function clampJoined(parts: readonly string[]): string {
  let kept = ''
  let seen = 0
  for (const part of parts) {
    for (const point of part) {
      if (seen === RESOLVER_ERROR_TEXT_LIMIT) return `${kept}… (обрезано)`
      kept += point
      seen += 1
    }
  }
  return kept
}

/**
 * Собственное строковое data-свойство объекта — или `null`.
 *
 * `getOwnPropertyDescriptor` у Proxy — тоже ловушка, и она вправе бросить, а у
 * отозванного Proxy бросает всегда. Любая ошибка рефлексии здесь означает ровно
 * одно: безопасного текста нет. Возвращённый дескриптор — обычный свежий объект,
 * поэтому `'value' in slot` и `slot.value` уже безопасны; accessor отсеивается
 * тем же условием, а не читается.
 */
function ownStringProperty(value: object, key: string): string | null {
  /* ЧТО ЭТОТ try НЕ ЗАКРЫВАЕТ. Он гасит ИСКЛЮЧЕНИЕ ловушки, но не отменяет её
     ПОБОЧНЫХ ЭФФЕКТОВ: `getOwnPropertyDescriptor` у Proxy — чужой код, и он
     вправе, например, подменить `String.prototype[Symbol.iterator]` и уронить
     форматирование уже ПОСЛЕ возврата отсюда. Это не чинится аккуратностью
     рефлексии; это закрывает барьер `describeThrownSafely`. */
  try {
    const slot = Object.getOwnPropertyDescriptor(value, key)
    if (!slot || !('value' in slot)) return null
    return typeof slot.value === 'string' ? slot.value : null
  } catch {
    return null
  }
}

/**
 * Описание брошенного значения. Тотальной эту функцию НАЗЫВАТЬ НЕЛЬЗЯ — см.
 * барьер `describeThrownSafely` ниже и честную формулировку гарантии там же.
 *
 * Прежняя редакция обещала «безопасную рефлексию любого значения» комментарием и
 * не делала этого кодом. `instanceof Error`
 * дёргает ловушку `getPrototypeOf`, а `error.name` и `error.message` — ловушку
 * `get` и наследованный getter. Аудит Codex предъявил `HostileError`, у которого
 * `get message()` бросает: исключение уходило наружу мимо всей границы и роняло
 * весь пакет — то самое, что R1 закрывал. Тем же путём уходили Proxy с бросающими
 * ловушками и отозванный Proxy.
 *
 * Поэтому здесь нет ни `instanceof`, ни единого прямого чтения свойства.
 * `typeof` и сравнение с `null` ловушек не имеют и безопасны на любом значении;
 * `name` и `message` читаются ТОЛЬКО как собственные data-дескрипторы.
 *
 * Значение никогда не приводится к строке. Причин две, и обе проверены.
 * `String(value)` зовёт чужой `Symbol.toPrimitive` или `toString` — у бросающего
 * Proxy это ловушка `get`, и она уронит границу; у `Error` с враждебным getter'ом
 * `Error.prototype.toString` прочитает `message` и уронит её тоже. А на символе
 * `String` не бросает вовсе — он возвращает `Symbol(описание)` и тем самым
 * выносит наружу чужой текст, который мы решили не выносить. (Бросает только
 * НЕЯВНОЕ приведение: `${'`${value}`'}`. Разница проверена, а не предположена.)
 *
 * Поэтому всё, для чего безопасного текста нет, описывается ТИПОМ — это правда
 * о значении, а не догадка о нём.
 */
export function describeThrown(error: unknown): string {
  const kind = error === null ? 'null' : typeof error
  let parts: readonly string[] | null = null

  if (kind === 'string') {
    parts = [error as string]
  } else if (kind === 'object') {
    const name = ownStringProperty(error as object, 'name')
    const message = ownStringProperty(error as object, 'message')
    if (message) parts = name ? [name, ': ', message] : [message]
    else if (name) parts = [name]
  }

  return clampJoined(parts ?? ['брошено значение типа ', kind])
}

/**
 * КОД ОШИБКИ БРОШЕННОГО ЗНАЧЕНИЯ — безопасно (10f-R R7).
 *
 * `error?.code` — чужой код на враждебном значении: у отозванного Proxy это
 * ловушка `get`, у объекта с getter'ом — сам getter. Аудит предъявил оба:
 * `catch`, отличавший `ENOENT`/`ENOTDIR`/`EEXIST` этим чтением, выпускал
 * ВТОРИЧНОЕ исключение и срывал fail-closed шаг, ради которого написан.
 *
 * Здесь `code` читается тем же способом, что `name` и `message`, — ТОЛЬКО как
 * собственный строковый data-дескриптор. Отдельной редакции этой процедуры в
 * проекте быть не должно, поэтому она живёт рядом с описателем и пользуется
 * его же рефлексией. Ничего не найдено или рефлексия отказала — `null`, то
 * есть «это не опознанный код ошибки», а не «код такой-то».
 */
export function thrownCode(error: unknown): string | null {
  if (typeof error !== 'object' || error === null) return null
  return ownStringProperty(error, 'code')
}

/**
 * Текст на случай, когда описать значение не удалось совсем.
 *
 * Строковый литерал и ничего больше: он не рефлексирует, не итерируется и не
 * форматируется, поэтому его выдача не может отказать по той же причине, по
 * которой отказало описание.
 */
export const UNDESCRIBABLE_THROWN = 'значение, которое описать не удалось'

/**
 * НЕЗАВИСИМЫЙ FAIL-CLOSED БАРЬЕР ВОКРУГ ВСЕГО ФОРМАТИРОВАНИЯ.
 *
 * ЧЕСТНАЯ ФОРМУЛИРОВКА ГАРАНТИИ. «Безопасная рефлексия любого Proxy» —
 * обещание невыполнимое, и давать его нельзя. Ловушка прокси есть чужой код,
 * исполняемый внутри нашей проверки, и её ПОБОЧНЫЕ ЭФФЕКТЫ рефлексией не
 * ограничены: аудит предъявил ловушку `getOwnPropertyDescriptor`, которая
 * подменяет `String.prototype[Symbol.iterator]` и роняет уже не рефлексию, а
 * обрезку текста — то есть шаг, где никакого чужого объекта давно нет. Сколько
 * ни делай рефлексию аккуратнее, отравить можно следующий шаг.
 *
 * Поэтому гарантия даётся не про рефлексию, а про ГРАНИЦУ, и она ровно одна:
 * **отказ форматировщика не покидает границу**. Что бы ни сломалось внутри
 * описания — рефлексия, обрезка, подменённый глобальный итератор, — кандидат
 * получает `resolverThrew` с постоянным текстом, хранилище не трогается, а
 * остальные кандидаты пакета продолжают прогон.
 *
 * Чего эта гарантия НЕ даёт, и об этом надо говорить вслух: подменённый
 * прототип остаётся подменённым до конца процесса. Границу это не роняет —
 * на её пути строки больше не итерируются, — но объявлять процесс здоровым
 * после такого прогона нельзя.
 */
export function describeThrownSafely(error: unknown): string {
  try {
    return describeThrown(error)
  } catch {
    return UNDESCRIBABLE_THROWN
  }
}
