/**
 * Словарь для перевода строк расхода на японский.
 *
 * Логика: в строке ищем ОБЪЕКТ (places) и ВИД РАСХОДА (kinds), собираем
 * «объект　вид　立替金». Ключи ищутся без учёта регистра, по вхождению;
 * побеждает самый длинный совпавший ключ, транспорт имеет приоритет.
 *
 * - overrides — точное совпадение всей строки, побеждает всё остальное
 * - places.kind — вид расхода по умолчанию для этого объекта (у храма 拝観料,
 *   у музея 入館料); он важнее общего «посещение» (kinds.generic)
 * - kinds.transport — включает разбор маршрутов: «такси Одавара — отель»
 * - route_terms — конечные точки маршрутов
 *
 * Чего в словаре нет — попадает в инвойс как есть и помечается предупреждением.
 */

export interface DictKind {
  keys: string[]
  jp: string
  /** Общее слово («посещение», «билет») — уступает виду расхода объекта. */
  generic?: boolean
  /** Транспорт — приоритет при поиске и разбор маршрута «откуда — куда». */
  transport?: boolean
  /** Услуги гида: суффикс 立替金 не добавляется. */
  no_advance?: boolean
}

export interface DictPlace {
  keys: string[]
  jp: string
  kind?: string
}

