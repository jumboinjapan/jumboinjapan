export type MatcherLexicon = typeof MATCHER_LEXICON

/**
 * Отпечаток словарей: SHA-256 канонической JSON-записи в порядке объявления.
 * Порядок элементов и ключей входит в отпечаток намеренно.
 */
export function matcherLexiconDigest(lexicon: MatcherLexicon = MATCHER_LEXICON): string {
  return `sha256:${createHash('sha256').update(JSON.stringify(lexicon), 'utf8').digest('hex')}`
}

/** Символьный класс регулярного выражения из строки символов (экранируются только спецсимволы класса). */
function charClass(chars: string): string {
  return `[${chars.replace(/[\\\]^-]/g, (c) => `\\${c}`)}]`
}
const LETTER_FOLDS = MATCHER_LEXICON.letterFolds.map(([from, to]) => [new RegExp(charClass(from), 'g'), to] as const)
const ARTICLES = new RegExp(`\\b(?:${MATCHER_LEXICON.articles.join('|')})\\s+`, 'gi')
const BRACKETS = new RegExp(charClass(MATCHER_LEXICON.bracketChars), 'g')
const DOTS = new RegExp(charClass(MATCHER_LEXICON.dotChars), 'g')
const MACRON_FOLDS = MATCHER_LEXICON.macronFolds.map(([from, to]) => [new RegExp(charClass(from), 'g'), to] as const)
const LONG_VOWEL = new RegExp(`(${charClass(MATCHER_LEXICON.romajiVowels)})\\1+`, 'g')

// ── Нормализация ────────────────────────────────────────────────────────

export function normalizeName(value: string | null | undefined): string {
  // Складывание букв (ё → е; э → е — «Сендай» = «Сэндай», один объект,
  // заведённый дважды), скобки, кавычки и японские точки → пробел, артикли,
  // всё небуквенное → пробел. Скобочное пояснение СОХРАНЯЕТСЯ: владелец
  // использует его как различитель — «Храм Риннодзи (Сэндай)» заведён
  // отдельно от никкоского «Храм Риннодзи». Таблицы — MATCHER_LEXICON.
  let s = String(value ?? '').toLowerCase()
  for (const [from, to] of LETTER_FOLDS) s = s.replace(from, to)
  return s
    .replace(BRACKETS, ' ')
    .replace(DOTS, ' ')
    .replace(ARTICLES, ' ')
    .replace(/[^\p{L}\p{N}]+/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim()
}

/** Родовые слова в начале русского названия и в конце английского. */
const GENERIC_HEAD = new RegExp(`^(?:${MATCHER_LEXICON.genericHead.join('|')})\\s+`)

/**
 * Родовое слово В КОНЦЕ — английский порядок: «Todai-ji Temple»,
 * «Hakone Ropeway», «Nijo Castle».
 *
 * Без этого правило №1 (родовое слово отдельно от ядра) для английских
 * названий просто НЕ РАБОТАЛО: GENERIC_HEAD привязан к началу строки,
 * а в английском родовое слово стоит в конце, поэтому head оставался
 * пустым и сравнивались целые строки вместе с родовым словом. Замер на
 * настоящих парах показал, что ошибка идёт в обе стороны сразу:
 *
 *   «Todai-ji Temple»   ⟷ «Todaiji»            0,50  — один храм, пропуск
 *   «Sengaku-ji Temple» ⟷ «Engaku-ji Temple»   0,86  — разные, почти блок
 *
 * Общее слово «temple» тянуло вверх непохожие названия и ничего не давало
 * похожим. Для коллектора это критично: внешние источники дают латиницу
 * и японский, то есть именно ту пару, где сравнение было слабее всего.
 */
const GENERIC_TAIL = new RegExp(`\\s+(?:${MATCHER_LEXICON.genericTail.join('|')})$`)

/**
 * Класс родового слова. Сравнивать родовые слова СТРОКАМИ нельзя: одно и
 * то же понятие приходит на трёх языках сразу.
 *
 *   «Fushimi Inari Taisha» ⟷ «Fushimi Inari Shrine»   taisha = shrine
 *   «Meiji Jingu»          ⟷ «Meiji Shrine»           jingu  = shrine
 *   «Храм Хасэдэра»        ⟷ «Hase-dera Temple»       храм   = dera = temple
 *
 * Первая версия правила «голова должна совпасть» сравнивала эти пары
 * посимвольно и давала ровный ноль — то есть на настоящих дублях
 * срабатывала ХУЖЕ, чем полное отсутствие правила. Поэтому сравниваются
 * не слова, а классы: «святилище» — это одна сущность, как бы её ни
 * записали, и она не равна «храму», хотя оба слова про культовое здание.
 */
/**
 * В один класс попадают только ПЕРЕВОДЫ И ТОЧНЫЕ СИНОНИМЫ, но не слова
 * из одной области. Проверено на живой базе: первая версия объединила
 * «канатную дорогу» и «горную железную дорогу» как «примерно одно и то же»,
 * и Hakone Ropeway (POI-000047) немедленно заблокировал Hakone Tozan
 * Railway (POI-000048) — два разных вида транспорта в одном городе, оба
 * с ядром «хаконе». По той же причине разведены сад и парк, озеро и пруд,
 * зоопарк и аквариум, долина и ущелье.
 */
const GENERIC_CLASS = new Map<string, string>(
  Object.entries(MATCHER_LEXICON.genericClass).flatMap(([cls, words]) => words.split('|').map((word) => [word, cls] as [string, string])),
)

export interface SplitName {
  head: string
  core: string
  full: string
}

export function splitName(value: string | null | undefined): SplitName {
  const normalized = normalizeName(value)
  if (!normalized) return { head: '', core: '', full: '' }

  const head = normalized.match(GENERIC_HEAD)
  if (head) {
    const core = normalized.slice(head[0].length).trim()
    // Название целиком состоит из родового слова («Синдзюку») — оно и есть ядро.
    if (core.length >= MATCHER_POLICY.nameCoreMinLength) return { head: head[0].trim(), core, full: normalized }
    return { head: '', core: normalized, full: normalized }
  }

  const tail = normalized.match(GENERIC_TAIL)
  if (tail) {
    const core = normalized.slice(0, normalized.length - tail[0].length).trim()
    if (core.length >= MATCHER_POLICY.nameCoreMinLength) return { head: tail[0].trim(), core, full: normalized }
  }

  return { head: '', core: normalized, full: normalized }
}

export function nameCore(value: string | null | undefined): string {
  return splitName(value).core
}

// ── Пространство имён коллекции ─────────────────────────────────────────

/**
 * ИМЯ КОЛЛЕКЦИИ НЕ ДОЛЖНО ЗАГЛУШАТЬ РАЗЛИЧАЮЩУЮ ЧАСТЬ ИМЕНИ.
 *
 * Именованная коллекция — это несколько САМОСТОЯТЕЛЬНЫХ объектов, у которых
 * общее начало имени. Родовое слово (правило №1) их не разводит: «Art House
 * Project» — не родовое слово, а имя собственное, и в справочнике его нет
 * и быть не может. В результате общая часть занимает большую долю строки,
 * триграммы совпадают, и разные объекты получают вес, близкий к порогу:
 *
 *   «Art House Project: Kadoya» ⟷ «Art House Project: Kinza»      0,7755
 *   «Art House Project: Go'o Shrine» ⟷ «Art House Project: Gokaisho» 0,8000
 *   «Этиго-Цумари: Мацунояма» ⟷ «Этиго-Цумари: Мацудай»           0,7727
 *
 * Ни одна пара не дубль: это разные дома арт-проекта в Хоммуре и разные
 * зоны Этиго-Цумари, каждая со своим адресом и своим билетом. Вес выше
 * DUPLICATE_REVIEW, и при координатах в пределах GEO_SAME_PLACE_M гейт
 * блокировал создание — то есть коллекцию нельзя было завести целиком.
 *
 * Решение структурное: если ОБЕ стороны объявляют коллекцию явным
 * разделителем, сравниваются отдельно имя коллекции и различающая часть,
 * и берётся МИНИМУМ — та же логика, что у пары «родовое слово / ядро».
 * Дубль обязан совпасть и по коллекции, и по объекту внутри неё. Поэтому
 * настоящий дубль с общим родителем по-прежнему находится: у него совпадает
 * и то, и другое.
 *
 * РАЗДЕЛИТЕЛЬ — ТОЛЬКО ДВОЕТОЧИЕ, и это решение по данным, а не по вкусу.
 * Локальный снимок 11.08.2026 (466 записей, состав полей ограничен: русские
 * имена есть у всех, английских и городов в снимке НЕТ): двоеточие стоит
 * в 13 именах и во всех тринадцати отделяет коллекцию от объекта
 * («Дом-проект: …» ×6, «Этиго-Цумари: …» ×6). Про латиницу этот снимок
 * не говорит ничего — там её нет. Тире в пробелах встречается дважды и означает
 * ровно противоположное — пояснение к тому же самому объекту: «Сюкубо —
 * ночлег в храме», «Ёсино — вишнёвые сады». Считать тире разделителем
 * коллекции значило бы резать имя пополам там, где оно единое.
 * Конвенция закреплена в docs/poi-standard.md: «если английское несёт
 * префикс („Art House Project: Kinza"), русское обязано нести его тоже».
 *
 * ОТВЕРГНУТО: искать общий префикс БЕЗ разделителя. Отличить коллекцию от
 * случайного совпадения начала строкой нельзя, а цена ошибки односторонняя:
 * сняв «общий префикс» у «Руины замка Сендай» и «Руины замка Сэндай», мы
 * потеряли бы единственный настоящий дубль этой формы. Явный разделитель
 * ставит владелец — это объявление, а не догадка.
 */
const NAMESPACE_SEPARATOR = new RegExp(charClass(MATCHER_LEXICON.namespaceSeparators))

/**
 * Минимальная длина каждой из двух частей. Отсекает двоеточие внутри
 * названия-цитаты: в базе есть «Выставка «Shinjuku Kabukicho Shunga
 * Exhibition: WA»», где после двоеточия остаётся «wa» — это не объект
 * коллекции, а часть заголовка выставки.
 */
// Значение — MATCHER_POLICY.namespacePartMinLength: читается при вызове, не при загрузке.

export interface NamespacedName {
  /** Имя коллекции, нормализованное. Пусто, если коллекции нет. */
  namespace: string
  /** Различающая часть, нормализованная. Без коллекции равна полному имени. */
  local: string
  /**
   * Те же две части В ИСХОДНОМ ВИДЕ. Сравнение обязано идти по ним, а не по
   * нормализованным: normalizeName снимает скобки, а именно в скобках живёт
   * уточнение места («Kadoya (Naoshima)»), по которому отличают настоящий
   * дубль от разных объектов. Отдав вниз нормализованную часть, мы уничтожили
   * бы признак раньше, чем его успели бы прочитать.
   */
  namespaceSource: string
  localSource: string
  full: string
}

export function splitNamespace(value: string | null | undefined): NamespacedName {
  const raw = String(value ?? '')
  const full = normalizeName(raw)
  // Разделитель ищется в СЫРОЙ строке: normalizeName вычищает пунктуацию,
  // то есть уничтожает признак раньше, чем его успели бы прочитать.
  const at = raw.search(NAMESPACE_SEPARATOR)
  const plain = { namespace: '', local: full, namespaceSource: raw, localSource: raw, full }
  if (at < 0) return plain
  const namespaceSource = raw.slice(0, at)
  const localSource = raw.slice(at + 1)
  const namespace = normalizeName(namespaceSource)
  const local = normalizeName(localSource)
  // Части короче namespacePartMinLength коллекцией не считаются: пустая часть,
  // двухсимвольный хвост заголовка и прочие случайные двоеточия не должны
  // приводить к тому, что от имени останется половина.
  const partMin = MATCHER_POLICY.namespacePartMinLength
  if (namespace.length < partMin || local.length < partMin) return plain
  return { namespace, local, namespaceSource, localSource, full }
}

// ── Уточнение в скобках ─────────────────────────────────────────────────

/**
 * УТОЧНЕНИЕ МЕСТА — ЭТО ПРИЗНАК НЕОДНОЗНАЧНОСТИ, А НЕ РАЗЛИЧИЯ.
 *
 * normalizeName намеренно СОХРАНЯЕТ содержимое скобок: владелец пишет туда
 * различитель тёзок («Храм Риннодзи (Сэндай)» против никкоского «Храм
 * Риннодзи»). Но у той же записи есть и вторая роль — уточнение того же
 * самого объекта: «Art House Project: Kadoya (Naoshima)» и «Art House
 * Project: Kadoya» это один дом. По строкам эти две роли неотличимы.
 *
 * Триграммы решали их одинаково плохо: лишнее слово в скобках забирает
 * заметную долю строки, и настоящий дубль опускался до 0,6087 — ниже порога
 * показа. Запись создавалась вторично, и никто об этом не узнавал.
 *
 * Правило: при СОВПАДАЮЩЕЙ основе и уточнении хотя бы у одной стороны вес
 * поднимается до 0,85 — того же потолка, что у вхождения по границе слова
 * в skeletonMatch. Это НАМЕРЕННО ниже DUPLICATE_BLOCK: сам по себе такой
 * вес не блокирует никогда. Разводит пару расстояние — у одного объекта
 * координаты совпадут, у тёзок в Никко и Сэндае разойдутся на 203 км, и
 * ветка опровержения снимет вопрос. Ровно то разделение труда, ради
 * которого координаты и заводились.
 *
 * Только круглые скобки. Кавычки-ёлочки — это цитирование, а не уточнение:
 * «Музей нэбута «Ва-Рассэ»» и «Музей Небута Ва Рассэ» — один музей, и
 * вынести «Ва-Рассэ» из основы значило бы развести настоящий дубль.
 */
const QUALIFIER = new RegExp(`${charClass(MATCHER_LEXICON.qualifierOpen)}([^${MATCHER_LEXICON.qualifierClose}]*)${charClass(MATCHER_LEXICON.qualifierClose)}`, 'g')

export interface QualifiedName {
  /** Имя без скобочной части. */
  base: string
  /** Содержимое скобок. Пусто, если скобок не было. */
  qualifier: string
  full: string
}

export function splitQualifier(value: string | null | undefined): QualifiedName {
  const raw = String(value ?? '')
  const full = normalizeName(raw)
  const inner: string[] = []
  const stripped = raw.replace(QUALIFIER, (_match, part: string) => {
    inner.push(part)
    return ' '
  })
  const base = normalizeName(stripped)
  const qualifier = normalizeName(inner.join(' '))
  // Имя, целиком состоящее из скобок, основы не имеет — уточнять нечего.
  if (!qualifier || !base) return { base: full, qualifier: '', full }
  return { base, qualifier, full }
}

// ── Письменность ────────────────────────────────────────────────────────

/**
 * Какой письменностью записана строка.
 *
 * Бинарное «кириллица или латиница» — ошибка на вырост: любой некириллический
 * текст оно объявляет латиницей, включая японский. Порталы уже отдают
 * японские названия (`Name (JA)` заведено в стандарте как сильнейший ключ
 * сверки), и как только они дойдут до матчера, «東大寺» будет объявлено
 * латиницей и сравнено с «Todaiji» как однописьменная пара.
 *
 * 'mixed' — это не «плохая строка», а частый и законный случай:
 * «teamLab Planets (Тоёсу)». Он назван отдельно именно потому, что
 * сравнивать такие строки как однописьменные нельзя.
 */
export type NameScript = 'latin' | 'cyrillic' | 'japanese' | 'mixed' | 'none'

export function nameScript(value: string | null | undefined): NameScript {
  const raw = String(value ?? '')
  const found: NameScript[] = []
  if (/[Ѐ-ӿԀ-ԯ]/.test(raw)) found.push('cyrillic')
  // Хирагана, катакана, CJK-иероглифы и катакана половинной ширины.
  if (/[぀-ゟ゠-ヿ一-鿿ｦ-ﾝ]/.test(raw)) found.push('japanese')
  if (/[A-Za-z]/.test(raw)) found.push('latin')
  if (!found.length) return 'none'
  return found.length === 1 ? found[0] : 'mixed'
}

// ── Свидетельство о коллекции ───────────────────────────────────────────

/**
 * Что мы знаем о том, одна ли это коллекция.
 *
 *   none        коллекцию объявила не каждая сторона — правило не работает
 *   same        РАВЕНСТВО ДОКАЗАНО: имена совпали посимвольно либо сошлись
 *               существующим механизмом транслитерации
 *   different   имена коллекций СРАВНИМЫ (одна письменность, для которой у
 *               нас есть посимвольное сравнение) и равенство не доказано
 *   unverified  имена коллекций сравнить нечем: разные письменности, и
 *               транслитерация равенства не подтвердила
 *
 * Различать 'same' и 'different' обязательно. Пока оба состояния назывались
 * одним словом 'compared', вывод «коллекции разные» приходилось доставать
 * из общего веса имени в другом слое — а вес считается по ЛУЧШЕЙ паре имён
 * и о конфликте на второй оси ничего не знает. Так «Дом-проект: Кадоя» /
 * «Art House Project: Kadoya» против «Дом-проект: Кадоя» /
 * «Echigo-Tsumari: Kadoya» блокировались как дубль по совпавшему русскому
 * имени, хотя английские имена относят записи к РАЗНЫМ коллекциям.
 */
export type CollectionEvidence = 'none' | 'same' | 'different' | 'unverified'

/**
 * ПЕРЕВЕДЁННОЕ ИМЯ КОЛЛЕКЦИИ НЕЛЬЗЯ НИ ПРИРАВНЯТЬ, НИ ВЫБРОСИТЬ.
 *
 * Объект внутри коллекции транслитерируется («Кадоя» = «Kadoya»), а имя
 * коллекции переводится: у «Дом-проект» и «Art House Project» общего скелета
 * нет вовсе. Отсюда две ошибки, и обе настоящие:
 *
 *   выбросить имя коллекции  → «Дом-проект: Кадоя» и «Echigo-Tsumari: Kadoya»
 *                              дают 0,85 по одному лишь совпавшему объекту,
 *                              и в 122 м гейт их блокирует. Ложная блокировка.
 *   приравнять имена коллекций → та же пара объявляется дублем без единого
 *                              доказательства. Хуже, потому что молча.
 *
 * Доказательство равенства признаётся ровно одно — СОВПАДЕНИЕ СКЕЛЕТОВ.
 * «Этиго-Цумари» ⟷ «Echigo-Tsumari» дают echigotsumari с обеих сторон: это
 * одно имя собственное, записанное двумя алфавитами. «Дом-проект» ⟷ «Art
 * House Project» не дают ничего общего — и вывод здесь не «разные», а
 * «неизвестно»: перевод выглядит ровно так же, как чужая коллекция.
 *
 * Консервативный исход для «неизвестно»: пара ПОКАЗЫВАЕТСЯ владельцу и
 * НИКОГДА не блокирует создание автоматически (см. screenNewPoi). Цена
 * ошибок несимметрична — ложная блокировка мешает завести законную точку и
 * заставляет обходить гейт силой, пропущенный дубль виден в отчёте
 * целостности. Поэтому недоказанное равенство коллекций не даёт блокировки,
 * а даёт остановку с объяснением.
 */
export function collectionEvidence(
  a: string | null | undefined,
  b: string | null | undefined,
): CollectionEvidence {
  const na = splitNamespace(a)
  const nb = splitNamespace(b)
  if (!na.namespace || !nb.namespace) return 'none'
  if (na.namespace === nb.namespace) return 'same'
  // СРАВНИМОСТЬ ОПРЕДЕЛЯЕТСЯ ПО ИМЕНИ КОЛЛЕКЦИИ, А НЕ ПО ВСЕМУ ИМЕНИ.
  //
  // Алфавит объекта и алфавит коллекции независимы: «Art House Project:
  // Кадоя» — латинская коллекция с кириллическим объектом. Смотреть на всё
  // имя целиком значило бы объявлять несравнимыми две ЛАТИНСКИЕ коллекции
  // только потому, что у одной из записей объект написан по-русски.
  //
  // Сравнимы только две строки ОДНОЙ письменности, и притом такой, для
  // которой у нас есть посимвольное сравнение: латиница или кириллица.
  // Японская строка, смешанная строка и строка без букв сравнимыми не
  // считаются — для них остаётся только доказательство транслитерацией.
  const ka = romajiSkeleton(na.namespaceSource)
  const kb = romajiSkeleton(nb.namespaceSource)
  if (ka.length >= MATCHER_POLICY.skeletonMinLength && ka === kb) return 'same'
  const sa = nameScript(na.namespaceSource)
  const sb = nameScript(nb.namespaceSource)
  if (sa === sb && (sa === 'latin' || sa === 'cyrillic')) return 'different'
  return 'unverified'
}

// ── Отношение уточнений ─────────────────────────────────────────────────

/**
 * Четыре состояния скобочного уточнения при СОВПАДАЮЩЕЙ основе.
 *
 *   none       основы разные — уточнения ни при чём
 *   one_sided  уточнение есть у одной стороны: «Kadoya» и «Kadoya (Naoshima)»
 *   agree      равенство ДОКАЗАНО: строки совпали посимвольно либо сошлись
 *              тем же механизмом транслитерации, что и всё остальное
 *   unverified уточнения есть у обеих, и ни равенство, ни различие
 *              доказать нечем
 */
export type QualifierRelation = 'none' | 'one_sided' | 'agree' | 'unverified'

/**
 * ДВЕ РАЗНЫЕ СТРОКИ В СКОБКАХ НИЧЕГО НЕ ДОКАЗЫВАЮТ.
 *
 * Прошлая версия этого правила объявляла расходящиеся уточнения «заявлением
 * владельца о различии» и снимала пару с разбора. Предпосылка неверна:
 * у матчера нет provenance имени. Строка в скобках приходит из портала,
 * из файла `--names`, из транслитерации по Поливанову или от модели —
 * человек её мог не писать вовсе. Цена ошибки видна сразу:
 *
 *   «Art House Project: Kadoya (East)» ⟷ «…(Восток)»          0,4250
 *   «Храм Риннодзи (Главный корпус)»  ⟷ «…(Main Hall)»        0,4186
 *
 * Это один и тот же объект с ПЕРЕВЕДЁННЫМ уточнением, и гейт пропускал обе
 * пары молча: вес ниже порога показа, а «различие» считалось доказанным.
 * Симметрично «(East)» ⟷ «(West)» тоже не доказаны как разные — просто
 * потому, что доказывать нечем.
 *
 * Поэтому исход у любой пары непустых несовпавших уточнений один:
 * 'unverified'. Не «одинаковые» и не «разные», а «неизвестно» — и такие
 * пары уходят владельцу отдельным каналом (см. screenNewPoi), а не
 * пропадают из разбора.
 *
 * ДОКАЗАТЕЛЬСТВОМ РАВЕНСТВА признаются ровно две вещи, обе уже существующие:
 * посимвольное совпадение после нормализации и совпадение скелетов ромадзи
 * («(Замок Аоба)» ⟷ «(Аоба)» → aoba). Ни списка переводов, ни allowlist,
 * ни нового числового порога здесь нет и быть не должно.
 *
 * ОТДЕЛЬНОГО КАНАЛА «ДОКАЗАННО РАЗНЫЕ» НЕТ НАМЕРЕННО. Он появится тогда,
 * когда во входе появится структурированный признак различия, проставленный
 * человеком, — не раньше. Две несовпавшие строки таким признаком не являются.
 */
export function qualifierRelation(
  a: string | null | undefined,
  b: string | null | undefined,
): QualifierRelation {
  const qa = splitQualifier(a)
  const qb = splitQualifier(b)
  if (!qa.base || qa.base !== qb.base) return 'none'
  if (!qa.qualifier && !qb.qualifier) return 'none'
  if (!qa.qualifier || !qb.qualifier) return 'one_sided'
  if (qa.qualifier === qb.qualifier) return 'agree'
  const ka = romajiSkeleton(qa.qualifier)
  const kb = romajiSkeleton(qb.qualifier)
  if (ka && ka === kb) return 'agree'
  return 'unverified'
}

// ── Ромадзи: мост между алфавитами ──────────────────────────────────────

export function stripDiacritics(value: string | null | undefined): string {
  const stripped = String(value ?? '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
  // Макроны (MATCHER_LEXICON.macronFolds): NFD их не разлагает единообразно.
  return MACRON_FOLDS.reduce((acc, [from, to]) => acc.replace(from, to), stripped)
}

const EN_GENERIC = new RegExp(`\\b(?:${MATCHER_LEXICON.enGeneric.join('|')})\\b`, 'g')

/**
 * Русские родовые слова — набор токенов, НЕ регулярка с `\b`.
 *
 * В JavaScript `\b` определён по ASCII, поэтому `/\bхрам\b/` не совпадает
 * с русским словом. Первая версия этого кода была написана с `\b` и молча
 * не снимала ни одного русского слова: «Храм Токэйдзи» превращалось
 * в «hramtokeiji» и не сходилось с «tokeiji».
 *
 * Тот же дефект живёт в src/lib/japantravel-event-intake.ts — все
 * контентные фильтры там построены на `\b` и на не-английском тексте
 * молча не срабатывают.
 */
const RU_GENERIC = new Set(MATCHER_LEXICON.ruGeneric)

/**
 * Обратная транслитерация Поливанова. Порядок ключей критичен —
 * многобуквенные сочетания разбираются раньше односимвольных, иначе
 * «дзи» распадётся на «д» + «з» + «и».
 */
const POLIVANOV = MATCHER_LEXICON.polivanov

export function cyrillicToRomaji(value: string | null | undefined): string {
  // Латинские части названия СОХРАНЯЮТСЯ. Прежний разбор выкидывал их
  // вместе с пунктуацией, и «teamLab Planets (Тоёсу)» сжималось до одного
  // слова «toyosu» — голого топонима, который совпадал с «Toyosu Fish
  // Market». Два совершенно разных объекта признавались дублями.
  const cleaned = String(value ?? '')
    .toLowerCase()
    .split(/[^a-zа-яё0-9]+/)
    .filter((token) => token && !RU_GENERIC.has(token))
    .join(' ')

  let out = ''
  let i = 0
  while (i < cleaned.length) {
    let matched = false
    for (const [ru, la] of POLIVANOV) {
      if (cleaned.startsWith(ru, i)) {
        out += la
        i += ru.length
        matched = true
        break
      }
    }
    if (!matched) {
      out += cleaned[i]
      i += 1
    }
  }
  return out
}

/**
 * «Скелет ромадзи» — общее представление для любого из трёх языков.
 *   «Храм Токэйдзи»   → tokeiji
 *   «Tokeiji Temple»  → tokeiji
 *   «Tōkei-ji Temple» → tokeiji
 */
export function romajiSkeleton(value: string | null | undefined): string {
  if (!value) return ''
  const raw = String(value)
  const hasCyrillic = /[Ѐ-ӿ]/.test(raw)
  let s = hasCyrillic ? cyrillicToRomaji(raw) : stripDiacritics(raw).toLowerCase()
  if (!hasCyrillic) s = s.replace(EN_GENERIC, ' ')
  return s
    .replace(/[^a-z0-9]+/g, '')
    // Долгота гласной в ромадзи записывается по-разному (oo / ou / ō / o).
    .replace(LONG_VOWEL, '$1')
    .trim()
}

/**
 * n-граммы имени (по политике — триграммы). Размер n — параметр алгоритма:
 * биграммы и триграммы дают разные веса одной паре, поэтому он в политике.
 * Набивка: n − 1 пробелов слева, один справа — как у прежних триграмм.
 */
function trigrams(value: string): Set<string> {
  const n = MATCHER_POLICY.ngramSize
  const padded = `${' '.repeat(n - 1)}${value} `
  const out = new Set<string>()
  for (let i = 0; i + n <= padded.length; i += 1) out.add(padded.slice(i, i + n))
  return out
}

function dice(a: string, b: string): number {
  if (!a || !b) return 0
  if (a === b) return 1
  const ta = trigrams(a)
  const tb = trigrams(b)
  let shared = 0
  for (const t of ta) if (tb.has(t)) shared += 1
  return (2 * shared) / (ta.size + tb.size)
}

/**
 * @param cityTokens скелеты названий городов обеих записей. Нужны, чтобы
 *   вхождение не срабатывало на голом топониме: «Sendai Castle Ruins» даёт
 *   скелет «sendai», и он является окончанием «rinnojisendai» (из «Храм
 *   Риннодзи (Сэндай)»). Без этой поправки руины замка Сэндай признавались
 *   дублем сэндайского храма Риннодзи с весом 0,9 — совпало только имя
 *   города, а оно есть у половины записей в любом городе.
 */
export function skeletonMatch(
  a: string | null | undefined,
  b: string | null | undefined,
  cityTokens: string[] = [],
): number {
  const sa = romajiSkeleton(a)
  const sb = romajiSkeleton(b)
  const minLen = MATCHER_POLICY.skeletonMinLength
  if (!sa || !sb || sa.length < minLen || sb.length < minLen) return 0
  // Совпадение скелетов, сводящееся к имени города, — не свидетельство.
  // «Канатная дорога Хаконе» и «Ботанический сад Хаконе» после снятия
  // родовых слов обе дают «hakone».
  if (sa === sb) return cityTokens.includes(sa) ? 0 : 1

  const [short, long] = sa.length <= sb.length ? [sa, sb] : [sb, sa]
  if (long.includes(short) && !cityTokens.includes(short)) {
    const extra = long.length - short.length
    // Вхождение засчитывается ТОЛЬКО как приставка или окончание и только
    // если лишняя часть — самостоятельное слово, а не пара букв.
    // Без этого «engakuji» ⊂ «sengakuji» давало 0,9 и сливало два разных
    // храма. Порог длины 5 (не 6) нужен для «Святилище Мэйдзи» → «meiji»
    // против «Meiji Jingū» → «meijijingu»: японское родовое слово
    // в английском остаётся в ромадзи, а в русском переводится.
    // 0.85 — НАМЕРЕННО ниже порога блокировки (DUPLICATE_BLOCK = 0.9).
    //
    // Вхождение одного названия в другое принципиально двусмысленно: это
    // либо дубль («Хасэдэра» внутри «Храм Хасэ Каннон (Хасэдэра)»), либо
    // отношение часть-целое («Тоёсу» внутри «Рыбный рынок Тоёсу»). Отличить
    // их по строкам нельзя, поэтому такие пары идут человеку на проверку,
    // а не блокируются автоматически. Блокирует только точное совпадение.
    const atBoundary = long.startsWith(short) || long.endsWith(short)
    if (
      atBoundary &&
      short.length >= MATCHER_POLICY.skeletonContainmentMinShort &&
      extra >= MATCHER_POLICY.skeletonContainmentMinExtra
    ) {
      return SIMILARITY_CEILING
    }
    return MATCHER_POLICY.skeletonContainmentFallback
  }

  // Нечёткое сходство скелетов — самый слабый из трёх сигналов, и его
  // приходится придерживать. «Тодайдзи» и «Тосёдайдзи» (два разных храма
  // Нары) дают по триграммам 0,74 — чуть выше порога 0,72. Коэффициент
  // 0,85 опускает такие пары ниже порога, не задевая настоящие совпадения:
  // те приходят либо точным равенством скелетов, либо вхождением по границе.
  const ga = trigrams(short)
  const gb = trigrams(long)
  let shared = 0
  for (const g of ga) if (gb.has(g)) shared += 1
  const fuzzy = (2 * shared) / (ga.size + gb.size)
  return roundScore(fuzzy * SIMILARITY_CEILING)
}

/**
 * Сходство родовых слов. Одна сторона без родового слова — не улика
 * против: «Todaiji» без слова «Temple» это тот же храм.
 */
function headSimilarity(a: string, b: string): number {
  if (!a || !b) return 1
  if (a === b) return 1
  const ca = GENERIC_CLASS.get(a)
  const cb = GENERIC_CLASS.get(b)
  // Оба слова известны: решает класс, а не написание. Разные классы —
  // это разные объекты («канатная дорога» против «ботанического сада»),
  // и здесь ноль стоит по делу.
  if (ca && cb) return ca === cb ? 1 : 0
  // Хотя бы одно слово вне справочника — падаем на посимвольное сравнение,
  // а не на ноль: неизвестное слово не должно отменять совпадение ядер.
  return Math.max(dice(a, b), MATCHER_POLICY.headUnknownFloor)
}

/**
 * Сходство двух названий: 0..1.
 *
 * Верхний слой — коллекция (см. splitNamespace). Он снимает общее имя
 * коллекции, когда его объявили ОБЕ стороны, и передаёт вниз две пары:
 * коллекция с коллекцией и объект с объектом. Ниже работает то же
 * сравнение, что и всегда, — оно про коллекции не знает.
 *
 * Исходов три, а не два:
 *   коллекции сравнимы    → минимум из двух весов, дубль требует обоих
 *   равенство не доказано → вес по объекту, но блокировать этим нельзя
 *   коллекции нет         → прежнее поведение без единого изменения
 *
 * Замер по локальному снимку 11.08.2026 (состав полей ограничен, имена RU):
 * правило меняет полосу решения ровно у ОДНОЙ пары — «Этиго-Цумари:
 * Мацунояма» ⟷ «Этиго-Цумари: Мацудай», 0,7727 → 0,4444. Это вторая,
 * независимая коллекция в снимке: правило структурное, а не подгонка под
 * дома арт-проекта.
 *
 * ОТВЕРГНУТО: распространять правило на случай, когда коллекцию объявила
 * ТОЛЬКО ОДНА сторона (сравнивать её объект с целым именем второй). Замер
 * на том же снимке дал новую ложную близость: «Исторический музей Мацудая»
 * ⟷ «Этиго-Цумари: Мацудай» поднимались с 0,3448 до 0,75, а музей стоит
 * внутри зоны — при координатах ближе 150 м это блокировка законной записи.
 *
 * ОТВЕРГНУТО: искать общий префикс без разделителя. Отличить коллекцию от
 * случайного совпадения начала строкой нельзя, а цена ошибки односторонняя:
 * сняв «общий префикс» у «Руины замка Сендай» и «Руины замка Сэндай», мы
 * потеряли бы настоящий дубль.
 */
export function nameSimilarity(
  a: string | null | undefined,
  b: string | null | undefined,
  cityTokens: string[] = [],
): number {
  const na = splitNamespace(a)
  const nb = splitNamespace(b)
  if (!na.full || !nb.full) return 0
  if (na.full === nb.full) return 1
  if (!na.namespace || !nb.namespace) return compareNames(a, b, cityTokens)

  // Части передаются В ИСХОДНОМ ВИДЕ: ниже работает разбор скобок,
  // а normalizeName их снимает.
  const localScore = compareNames(na.localSource, nb.localSource, cityTokens)

  // Равенство коллекций не доказано транслитерацией. Вес считается по одной
  // лишь различающей части — это ПОЛОВИНА нужного свидетельства, поэтому
  // screenNewPoi такой парой не блокирует, а останавливает с объяснением.
  // Обнулить вес нельзя: тогда один и тот же дом, записанный по-русски и
  // по-английски, перестал бы находиться вовсе.
  if (collectionEvidence(a, b) === 'unverified') {
    return roundScore(Math.min(localScore, SIMILARITY_CEILING))
  }

  // Дубль обязан совпасть И ПО КОЛЛЕКЦИИ, И ПО ОБЪЕКТУ — минимум, как
  // у пары «родовое слово / ядро». Разные коллекции с одинаковым объектом
  // и одна коллекция с разными объектами одинаково не дубли.
  return roundScore(Math.min(compareNames(na.namespaceSource, nb.namespaceSource, cityTokens), localScore))
}

/** Сходство двух названий БЕЗ учёта коллекции. */
function compareNames(
  a: string | null | undefined,
  b: string | null | undefined,
  cityTokens: string[] = [],
): number {
  const sa = splitName(a)
  const sb = splitName(b)
  if (!sa.full || !sb.full) return 0
  if (sa.full === sb.full) return 1

  const scriptA = /[Ѐ-ӿ]/.test(sa.full) ? 'cyr' : 'lat'
  const scriptB = /[Ѐ-ӿ]/.test(sb.full) ? 'cyr' : 'lat'

  // Между алфавитами посимвольные меры бесполезны — только скелет.
  //
  // Результат ограничен сверху 0.85, то есть НИКОГДА не блокирует сам по
  // себе. Межалфавитное сравнение — цепочка допущений: транслитерация по
  // Поливанову, снятие родовых слов, схлопывание долгих гласных. На выходе
  // от названия остаётся ядро, и если это ядро — топоним, разные объекты
  // одного места сливаются. Замерено на живой базе:
  //   «Гора Асахидакэ» ⟷ «Asahidake Onsen Village»   обе → asahidake
  //   «Toyosu Market»  ⟷ «Тоёсу (район)»             обе → toyosu
  // Ни одна пара не дубль. Поэтому межалфавитное совпадение всегда
  // показывается владельцу, но решение остаётся за ним; блокирует только
  // согласие в пределах одного алфавита.
  if (scriptA !== scriptB) return Math.min(skeletonMatch(a, b, cityTokens), SIMILARITY_CEILING)

  // ВНУТРИ ОДНОГО АЛФАВИТА СКЕЛЕТ НЕ ПРИМЕНЯЕТСЯ.
  //
  // Соблазн его включить велик, и я его проверил на живой базе: снимая
  // родовые слова, скелет оставляет от названия голый топоним, и все
  // объекты вокруг одного места схлопываются в одну строку. Прогон дал
  // 17 ложных блокировок на 431 записи, среди них:
  //   «Рыбный рынок Тоёсу» ⟷ «Тоёсу (район)»          обе → toyosu
  //   «Храм Тюдзэндзи»     ⟷ «Озеро Тюдзэндзи»        обе → chuzenji
  //   «Онсэн Асахидакэ»    ⟷ «Гора Асахидакэ»         обе → asahidake
  //   «Смотровая Shibuya Sky» ⟷ «Сибуя»
  // Поправка на siteCity здесь не спасает: Тоёсу и Тюдзэндзи — не слаги
  // городов, а произвольные топонимы внутри названия, и заранее их
  // списком не перечислить.
  //
  // Ложная блокировка хуже пропущенного дубля: она мешает завести
  // законную точку, и владелец начинает обходить гейт силой.
  // Пробелы и дефисы в ромадзи расставляются произвольно: «Todai-ji»,
  // «Todaiji» и «Todai ji» — одно слово, записанное тремя способами, и
  // ни один из них не «правильный». Поэтому ядра сравниваются дважды:
  // как есть и слитно, берётся лучший результат. Слитное сравнение может
  // только поднять вес, и поднимает его ровно там, где расхождение было
  // в расстановке пробелов, — «hakone ropeway» и «hakone botanical garden»
  // слитно так же далеки, как и раздельно.
  const despace = (s: string) => s.replace(/\s+/g, '')
  const coreScore = Math.max(dice(sa.core, sb.core), dice(despace(sa.core), despace(sb.core)))
  const headScore = headSimilarity(sa.head, sb.head)
  const score = Math.min(coreScore, headScore)

  // Родовое слово есть только у ОДНОЙ стороны — потолок 0,85, как
  // у межалфавитного сравнения, и по той же причине.
  //
  // Снятие родового слова оставляет от названия ядро, и если это ядро —
  // топоним, разница между дублем и отношением «часть-целое» исчезает:
  //   «Todai-ji Temple» ⟷ «Todaiji»        один храм
  //   «Toyosu Market»   ⟷ «Тоёсу (район)»  рынок внутри района
  // Обе пары дают ровно 1,0, и различить их по строкам нечем. Живая база
  // подтвердила: без потолка вторая пара (POI-000314 и POI-000324)
  // блокировалась как дубль. Потолок отправляет обе владельцу, а разводит
  // их расстояние — если координаты есть, то у одного места они совпадут,
  // а у рынка с районом разойдутся.
  const oneSidedHead = Boolean(sa.head) !== Boolean(sb.head)
  const capped = oneSidedHead ? Math.min(score, SIMILARITY_CEILING) : score

  // Уточнение в скобках при совпадающей основе (см. qualifierRelation).
  // Поднимаются только одностороннее и согласное: там различить дубль
  // и уточнение той же записи строкой нельзя, и вопрос решает расстояние.
  // Расходящиеся уточнения не поднимаются — владелец уже сказал, что это
  // разные объекты.
  const qualifier = qualifierRelation(a, b)
  if (qualifier === 'one_sided' || qualifier === 'agree') {
    return roundScore(Math.max(capped, SIMILARITY_CEILING))
  }

  return roundScore(capped)
}

/**
 * Отношение «часть — целое»: «Роппонги» и «Роппонги Хиллз», «Синдзюку» и
 * «Синдзюку Гёэн». Это НЕ дубли, а кандидат в Parent POI. Путать нельзя:
 * слияние такой пары уничтожит настоящую запись.
 */
export function containmentRelation(
  a: string | null | undefined,
  b: string | null | undefined,
): 'a_is_parent' | 'b_is_parent' | null {
  const ca = nameCore(a)
  const cb = nameCore(b)
  const minLen = MATCHER_POLICY.containmentCoreMinLength
  if (!ca || !cb || ca === cb || ca.length < minLen || cb.length < minLen) return null
  if (cb.startsWith(`${ca} `) || cb.endsWith(` ${ca}`)) return 'a_is_parent'
  if (ca.startsWith(`${cb} `) || ca.endsWith(` ${cb}`)) return 'b_is_parent'
  return null
}

