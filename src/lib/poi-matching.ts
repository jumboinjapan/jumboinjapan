/**
 * Ось сравнения имён.
 *
 *   ru     русское имя против русского
 *   en     английское против английского
 *   cross  межалфавитный fallback: ru↔en или en↔ru
 *
 * RU и EN — НЕЗАВИСИМЫЕ ВЫРОВНЕННЫЕ ОСИ, когда обе стороны заполнены:
 * это два разных описания одного и того же, сделанных разными людьми
 * в разное время, и расхождение между ними — сигнал, а не шум.
 *
 * Межалфавитные пары равноправным четвёртым голосом НЕ являются. Между
 * алфавитами сравнение сводится к транслитерации и не умеет отличить
 * перевод от чужого имени; если выровненная ось доступна, межалфавитная
 * пара к свидетельству ничего не добавляет, зато добавляет шум. Поэтому
 * cross-свидетельство собирается ТОЛЬКО тогда, когда ни одной выровненной
 * оси нет — то есть у одной из записей нужного имени просто не заполнено.
 * На ранжирование это не влияет: вес по-прежнему берётся как лучший
 * из всех четырёх пар.
 */
export type MatchAxis = 'ru' | 'en' | 'cross'

/** Свидетельство одной сравнённой оси. */
export interface MatchEvidence {
  axis: MatchAxis
  /** Какая именно пара имён: 'ru↔ru', 'en↔en', 'ru↔en', 'en↔ru'. */
  basis: string
  score: number
  collection: CollectionEvidence
  qualifier: QualifierRelation
}

export interface PoiMatch {
  candidate: PoiLike
  score: number
  sameCity: boolean
  /** Расстояние в метрах, если координаты есть у обеих записей. */
  distanceM: number | null
  /** По какой паре имён набран вес — для объяснимости в отчёте. */
  basis: string
  /**
   * Свидетельства ВСЕХ фактически сравнённых осей, а не только победившей.
   *
   * До 13.08.2026 здесь хранилось отношение коллекций и уточнений только
   * той пары, которая дала максимальный вес. Это схлопывало RU, EN и
   * межалфавитный fallback в одну правду и стирало противоречие: у пары
   * с одинаковыми русскими именами и английскими «Minamidera (West)» /
   * «Minamidera (East)» побеждала ru↔ru с весом 1, а английское
   * расхождение исчезало вместе с остальными осями.
   */
  evidence: MatchEvidence[]
  /**
   * ВСЕ структурные расхождения идентичности, типизированные. Низкий вес
   * сам по себе расхождением не считается — мало ли почему два имени
   * не похожи. Видов может быть несколько одновременно, и ни один из них
   * не отменяет остальные.
   */
  issues: IdentityIssue[]
}

/**
 * Вид расхождения идентичности. Виды НЕ взаимоисключающие: у одного
 * кандидата их бывает несколько сразу, и каждый приходит со своей оси.
 *
 * Реальный случай: RU «Дом-проект: Кадоя (Восток)» против «…(Запад)» —
 * уточнения не сверены; EN «Art House Project: Kadoya» против
 * «Echigo-Tsumari: Kadoya» — коллекции разные. Пока каналы были
 * взаимоисключающими и разбор прерывался на первом найденном виде,
 * второе расхождение исчезало из вердикта, причин, Notes и отчёта.
 */
export type IdentityIssueKind = 'collection_unverified' | 'collection_conflict' | 'qualifier_unverified'

export interface IdentityIssue {
  kind: IdentityIssueKind
  axis: MatchAxis
  /** Пара имён, на которой расхождение обнаружено. */
  basis: string
  score: number
}

const IDENTITY_ISSUE_LABEL: Record<IdentityIssueKind, string> = {
  collection_unverified: 'имена коллекций сравнить нечем',
  collection_conflict: 'коллекции разные',
  qualifier_unverified: 'уточнения в скобках не сверены',
}

/** Человекочитаемый список расхождений — для причин, Notes и отчёта. */
export function describeIdentityIssues(issues: IdentityIssue[]): string {
  return issues.map((i) => `${IDENTITY_ISSUE_LABEL[i.kind]} (${i.basis})`).join(', ')
}

/**
 * Типизированные расхождения по ВСЕМ сравнённым осям. Одна ось может дать
 * сразу два вида: коллекции разные И уточнения не сверены.
 */
function identityIssuesOf(evidence: MatchEvidence[]): IdentityIssue[] {
  const out: IdentityIssue[] = []
  for (const e of evidence) {
    const where = { axis: e.axis, basis: e.basis, score: e.score }
    if (e.collection === 'unverified') out.push({ kind: 'collection_unverified', ...where })
    if (e.collection === 'different') out.push({ kind: 'collection_conflict', ...where })
    if (e.qualifier === 'unverified') out.push({ kind: 'qualifier_unverified', ...where })
  }
  return out
}

/** Ранжированное сопоставление кандидата со всей базой. */
export function matchPoi(
  input: { nameRu: string; nameEn?: string; siteCity?: string } & GeoPoint,
  existing: PoiLike[],
): PoiMatch[] {
  const matches: PoiMatch[] = []
  for (const record of existing) {
    // Названия городов обеих записей — исключаются из сравнения как
    // самостоятельное основание для совпадения.
    const cityTokens = [romajiSkeleton(input.siteCity), romajiSkeleton(record.siteCity)].filter(
      (token) => token.length >= MATCHER_POLICY.cityTokenMinLength,
    )
    const pairs: Array<[string, string | undefined, string, MatchAxis]> = [
      [input.nameRu, record.nameRu, 'ru↔ru', 'ru'],
      [input.nameEn ?? '', record.nameEn, 'en↔en', 'en'],
      [input.nameRu, record.nameEn, 'ru↔en', 'cross'],
      [input.nameEn ?? '', record.nameRu, 'en↔ru', 'cross'],
    ]
    let best = 0
    let basis = ''
    const aligned: MatchEvidence[] = []
    const fallback: MatchEvidence[] = []
    for (const [x, y, label, axis] of pairs) {
      if (!x || !y) continue
      const score = nameSimilarity(x, y, cityTokens)
      // Вес — по-прежнему лучший из ВСЕХ четырёх пар: ранжирование не
      // меняется, меняется только то, что сохраняется как свидетельство.
      if (score > best) {
        best = score
        basis = label
      }
      const item: MatchEvidence = {
        axis,
        basis: label,
        score: roundScore(score),
        collection: collectionEvidence(x, y),
        qualifier: qualifierRelation(x, y),
      }
      if (axis === 'cross') fallback.push(item)
      else aligned.push(item)
    }
    // Межалфавитный fallback — только при отсутствии выровненных осей.
    const evidence = aligned.length ? aligned : fallback
    const distanceM = haversineMeters(input, record)
    // Запись без единого общего слова, но в тридцати метрах, всё равно
    // попадает в выдачу: имя может быть записано иначе (по-японски,
    // по названию комплекса), а место то же самое.
    const nearby = distanceM !== null && distanceM <= GEO_NEIGHBOUR_M
    if (best <= 0 && !nearby) continue
    matches.push({
      candidate: record,
      score: roundScore(best),
      sameCity: Boolean(input.siteCity && record.siteCity && input.siteCity === record.siteCity),
      distanceM,
      basis: basis || (nearby ? 'geo' : ''),
      evidence,
      issues: identityIssuesOf(evidence),
    })
  }
  // Совпадение в том же городе весомее: тёзок вроде «Храм Риннодзи»
  // в Японии много, и город — главный различитель. Близость по координатам
  // весомее города: город — это слаг длиной в слово, координаты — точка.
  const rank = (m: PoiMatch) =>
    m.score +
    (m.sameCity ? MATCHER_POLICY.rankSameCityBonus : 0) +
    (m.distanceM !== null && m.distanceM <= GEO_SAME_PLACE_M ? MATCHER_POLICY.rankSamePlaceBonus : 0)
  matches.sort((a, b) => rank(b) - rank(a))
  return matches
}

