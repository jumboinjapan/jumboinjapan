/**
 * Русская микротипографика на рендере.
 *
 * Зачем это существует. Аудит 2026-07-29 (docs/typography-audit-2026-07-29.md)
 * показал: неразрывных пробелов на сайте не было вообще — ноль на 1,8 млн
 * символов русского текста, при том что мест, где они нужны, около 19 900.
 * Расставить их руками нельзя: 68 файлов кода и 4,5 тысячи записей Airtable,
 * плюс каждый новый абзац снова придёт без них. Поэтому текст типографируется
 * на выводе, а не в источнике.
 *
 * ГДЕ ПРИМЕНЯЕТСЯ. В отображающих компонентах через typoDeep(props) — то есть
 * на границе показа, а не на границе чтения данных. Это принципиально:
 * бизнес-логика (tour-pricing разбирает программу дня по подстрокам
 * «частный транспорт», working-hours парсит часы) продолжает видеть исходный
 * текст без неразрывных пробелов. Не переносить вызовы в слой Airtable.
 *
 * ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ. Правила, которые не отличают верный случай от
 * неверного без понимания смысла, оставлены людям и разовым скриптам:
 *   — дефис в числовом диапазоне (1-2 → 1–2): неотличим от японского адреса
 *     «Асакуса, 1-32-11» и телефона;
 *   — десятичная точка (2.5 → 2,5): неотличима от короткой даты 18.07;
 *   — кавычки-ёлочки: определить границы цитаты регулярным выражением нельзя.
 * Эти случаи чинятся в данных (см. scripts/fix-airtable-typography.mjs) и
 * ловятся на входе скриптом npm run check:typography.
 */

const NBSP = ' '

/** Однобуквенные предлоги и союзы, которые не должны висеть в конце строки (R30). */
const SINGLE_LETTER = 'вВкКсСоОуУиИаАяЯ'

/**
 * Единицы измерения, которые не должны отрываться от числа (R36, R38).
 * Длинные варианты идут первыми: альтернация в JS берёт первое совпавшее,
 * иначе «м» съело бы начало «мин».
 *
 * Границы слова здесь и ниже задаются через (?![А-Яа-яЁё]), а не через \b:
 * в JavaScript \w — это [A-Za-z0-9_], поэтому \b рядом с кириллицей
 * срабатывает не там, где ожидается, и правило молча не применяется.
 */
const UNITS = 'мин|сек|мм|см|км|кг|га|°C|°|м|ч|г|л'
const WORD_UNITS = 'минут|минуты|часов|часа|дней|дня|метров|километров'

const REPLACEMENTS: Array<[RegExp, string]> = [
  // Три точки — один символ многоточия (R45). После ?/! ставится две точки (R51).
  [/\.\.\./g, '…'],
  [/([?!])…/g, '$1..'],

  // Случайные сдвоенные пробелы (C.5). Переводы строк не трогаем.
  [/[^\S\n]{2,}/g, ' '],

  // Дефис в роли тире между словами (R15): «цель центра - представить оперу».
  [/(?<=[А-Яа-яЁё0-9)»]) -+ (?=[А-Яа-яЁё0-9(«])/g, ` — `],

  // Неразрывный пробел после однобуквенных предлогов и союзов (R30).
  // Повтор нужен из-за перекрывающихся совпадений: «и в Токио».
  [new RegExp(`(^|[\\s(«„—–])([${SINGLE_LETTER}]) (?=[А-Яа-яЁё0-9])`, 'g'), `$1$2${NBSP}`],
  [new RegExp(`(^|[\\s(«„—–])([${SINGLE_LETTER}]) (?=[А-Яа-яЁё0-9])`, 'g'), `$1$2${NBSP}`],

  // Неразрывный пробел перед длинным тире (R16, R44): иначе тире уезжает
  // на новую строку и читается как реплика прямой речи.
  [/ +—/g, `${NBSP}—`],

  // Число и единица измерения не разрываются (R36, R38): «40 минут», «900 °C».
  [new RegExp(`(\\d) (?=(?:${UNITS})(?![А-Яа-яЁё]))`, 'g'), `$1${NBSP}`],
  [new RegExp(`(\\d) (?=(?:${WORD_UNITS})(?![А-Яа-яЁё]))`, 'g'), `$1${NBSP}`],

  // Части сокращений связываются неразрывным пробелом (R73): т. д., т. е.
  [/(?<![А-Яа-яЁёA-Za-z])т\. ?([депк])\./g, `т.${NBSP}$1.`],

  // Знак номера не отрывается от числа (R86).
  [/№ ?(?=\d)/g, `№${NBSP}`],
]

const CYRILLIC = /[А-Яа-яЁё]/

/**
 * Типографирует строку русского текста. Строки без кириллицы (пути, slug'и,
 * латинские названия, URL) возвращаются как есть.
 */
export function typo(input: string): string {
  if (!input || !CYRILLIC.test(input)) return input
  let out = input
  for (const [re, to] of REPLACEMENTS) out = out.replace(re, to)
  return out
}

/**
 * Ключи, значения которых типографировать нельзя: они участвуют в логике,
 * маршрутизации или сравнении, а не показываются как текст.
 */
const SKIP_KEYS = new Set([
  'id', 'key', 'slug', 'href', 'url', 'src', 'image', 'imagePath', 'heroImage',
  'heroImagePath', 'photo', 'photoPath', 'icon', 'className', 'class', 'style',
  'type', 'kind', 'mode', 'status', 'state', 'variant',
  'email', 'tel', 'phone', 'lang', 'locale', 'placeId', 'poiId', 'recordId',
  'canonical', 'canonicalUrl', 'target', 'rel', 'action', 'method',
])
// 'name', 'alt' и 'value' сознательно НЕ в списке: это видимый текст —
// названия точек, подписи изображений, правая колонка сводок вида
// {label: 'ФОРМАТ', value: 'Частный тур с русскоязычным гидом'}. Значения
// <option value> под удар не попадают: фильтры (EventsFiltersForm,
// RestaurantsFilter, HotelsExplorer) типографер не подключают вовсе — они
// ищут и сравнивают по сырому тексту, а показывают его через карточки,
// которые типографируют уже сами. Латинские значения типографер и так
// возвращает как есть — typo() выходит сразу, если в строке нет кириллицы.

function isReactNode(value: object): boolean {
  return '$$typeof' in value || 'props' in value
}

/**
 * Рекурсивно типографирует все строки в объекте или массиве. Возвращает новое
 * значение; исходное не мутируется. React-элементы, функции и ключи из
 * SKIP_KEYS проходят насквозь.
 */
export function typoDeep<T>(value: T): T {
  if (typeof value === 'string') return typo(value) as unknown as T
  if (!value || typeof value !== 'object') return value
  if (Array.isArray(value)) return value.map(item => typoDeep(item)) as unknown as T
  if (isReactNode(value)) return value
  if (value instanceof Date) return value

  const out: Record<string, unknown> = {}
  for (const [key, item] of Object.entries(value)) {
    out[key] = SKIP_KEYS.has(key) ? item : typoDeep(item)
  }
  return out as unknown as T
}
