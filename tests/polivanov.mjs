#!/usr/bin/env node
/**
 * Тесты прямой транслитерации по Поливанову.
 *
 *   npm run test:polivanov
 *
 * Спорные правила закреплены здесь ЦИФРАМИ ЗАМЕРА, а не ссылкой на
 * учебник: счёт по 394 парам имён из живой базы стоит в комментарии
 * к каждому такому случаю. Полный прогон по корпусу — check:polivanov.
 */

import {
  romajiToCyrillic,
  kanaToCyrillic,
  poiNameToRu,
  poiNameFromKana,
  POLIVANOV_EXCEPTIONS,
} from '../src/lib/polivanov.ts'
import { splitName } from '../src/lib/poi-matching.ts'

let passed = 0
const failures = []
const check = (label, actual, expected) => {
  if (actual === expected) passed += 1
  else failures.push(`${label}\n    ожидалось: ${expected}\n    получено:  ${actual}`)
}
const t = (romaji, expected) => check(`«${romaji}»`, romajiToCyrillic(romaji).value, expected)
const n = (en, expected) => check(`«${en}»`, poiNameToRu(en).nameRu, expected)

// ── Ряды каны ───────────────────────────────────────────────────────────
t('shibuya', 'сибуя')            // し = си, не «ши»
t('hachimangu', 'хатимангу')     // ち = ти, не «чи»
t('tsurugaoka', 'цуругаока')     // つ = цу
t('fushimi', 'фусими')
t('toshogu', 'тосёгу')           // しょ = сё
t('kanazawa', 'канадзава')       // ざ = дза, не «за»
t('todaiji', 'тодайдзи')         // じ = дзи
t('ryokan', 'рёкан')
t('kegon', 'кэгон')              // け = кэ

// ── Долгие гласные и удвоение ───────────────────────────────────────────
t('nikko', 'никко')              // っ — удвоение согласной
t('sapporo', 'саппоро')
t('toukyou', 'токио')            // долгота «ou» схлопывается до поиска в исключениях
t('juuniko', 'дзюнико')

// ── Дифтонги: спор решён счётом по живой базе ───────────────────────────
t('nusamai', 'нусамай')          // ai → ай, 34 случая против 3
t('meiji', 'мэйдзи')             // ei → эй, 12 против 0
t('heian', 'хэйан')              // «эй» действует и перед гласной
t('oishi', 'оиси')               // oi → ои, 0 случаев «ой» против 5
t('koishikawa', 'коисикава')
t('byodoin', 'бёдоин')

// ── ん перед йотированной ────────────────────────────────────────────────
// Апостроф в ромадзи — единственный признак, отличающий ん+я от にゃ.
check('«Daikan\'yama» — твёрдый знак', romajiToCyrillic("daikan'yama").value, 'дайканъяма')
check('«nya» без апострофа — にゃ', romajiToCyrillic('hanyama').value, 'ханяма')

// ── Исключения канона ───────────────────────────────────────────────────
t('hakone', 'хаконе')            // по Поливанову «Хаконэ», но так не ищут
check('исключения заданы явно', Object.keys(POLIVANOV_EXCEPTIONS).length > 20, true)

// ── Заимствования не транслитерируются ──────────────────────────────────
{
  // Заимствование остаётся английским ЦЕЛИКОМ: половина транслитерации
  // и половина латиницы («Токио Skytree») читается хуже обоих вариантов.
  const r = poiNameToRu('Tokyo Skytree')
  check('заимствование целиком английское', r.nameRu, 'Tokyo Skytree')
  check('и помечено', r.keptLatin.join(), 'Skytree')
  check('с предупреждением', r.warnings.length > 0, true)
  // Родовое слово при этом всё равно переводится — оно про тип объекта,
  // а не про имя. В базе ровно так: «Смотровая Shibuya Sky», «Музей Nintendo».
  check('родовое слово переводится', poiNameToRu('Shibuya Sky Observation Deck').nameRu, 'Смотровая Shibuya Sky')
  check('ничего не теряется', poiNameToRu('Umeda Sky Building').nameRu, 'Umeda Sky Building')
}

// ── Сборка имени POI ────────────────────────────────────────────────────
n('Todai-ji Temple', 'Храм Тодайдзи')
n('Osaka Castle', 'Замок Осака')
n('Kegon Waterfall', 'Водопад Кэгон')
n('Tsurugaoka Hachimangu Shrine', 'Святилище Цуругаока Хатимангу')
n('Nusamai Bridge', 'Мост Нусамай')
n('Yajiro Onsen', 'Горячие источники Ядзиро')      // родовое слово по-японски
n('Hakone Botanical Garden', 'Ботанический сад Хаконе')  // составное родовое
n('Tokugawa Mausoleum', 'Мавзолей Токугава')
n('Takaosan', 'Гора Такао')                        // -сан снимается

// «-дзи», «-ин», «-гу» — часть имени, а не родовое слово. В базе стоят
// «Кинкакудзи» и «Цуругаока Хатимангу», а не «Храм Кинкаку».
n('Kinkakuji', 'Кинкакудзи')
n('Ginkakuji', 'Гинкакудзи')
// «-яма» тоже остаётся: «Арасияма» это местность, а не «гора Араси».
n('Arashiyama', 'Арасияма')

// Хвост после запятой — уточнение места, город стоит в отдельном поле.
n('Hotokuji Temple, Kiryu', 'Храм Хотокудзи')
// Скобочное пояснение — то же имя другой записью.
n('Kegon Waterfall (Kegon no taki)', 'Водопад Кэгон')

// ── Японские бренды — всегда латиницей ──────────────────────────────────
//
// Решение владельца, и причина не в «иностранности»: 任天堂 и 三菱 Поливанов
// разбирает без труда. Без списка бренды кололись произвольно — по тому,
// укладывается ли латинская запись в открытые слоги:
//   nintendo, toshiba, mitsubishi  → кириллица
//   suntory, panasonic, yakult     → латиница (не разбираются)
// Suntory ничуть не менее японский, чем Mitsubishi.
n('Nintendo Museum', 'Музей Nintendo')
n('Toshiba Science Museum', 'Музей Toshiba')
n('Suntory Museum of Art', 'Художественный музей Suntory')
// «Canon» и «Kirin» читаются как ромадзи — без ветки брендов стали бы
// «Канон» и «Кирин».
n('Canon Gallery', 'Галерея Canon')
// Бренд НЕ утягивает в латиницу остальное имя: 一号館 это обычное слово.
n('Mitsubishi Ichigokan Museum', 'Музей Mitsubishi Итигокан')
{
  const r = poiNameToRu('Nintendo Museum')
  check('имя из бренда готово к записи', r.confidence, 1)
  check('и бренд отмечен', r.warnings.some((w) => /Nintendo/.test(w)), true)
}

// ── Служебные слова не протекают в латинское ядро ───────────────────────
// «Suntory Museum of Art» давало «Художественный музей Suntory of Art»:
// предлог повисал без существительного, ушедшего в родовое слово.
n('Osaka Museum of History', 'Исторический музей Осака')

// ── Значимое определение не теряется молча ──────────────────────────────
{
  const r = poiNameToRu('Tokyo National Museum')
  check('«National» отброшено с предупреждением', r.warnings.some((w) => /National/.test(w)), true)
}

// ── Совместимость с матчером ────────────────────────────────────────────
// Собранное имя обязано разбираться GENERIC_HEAD: иначе новая запись не
// сопоставится с уже заведёнными и гейт пропустит дубль.
{
  const built = poiNameToRu('Todai-ji Temple').nameRu
  check('матчер видит родовое слово', splitName(built).head, 'храм')
  check('и ядро', splitName(built).core, 'тодайдзи')
}


// ── Кана → кириллица ────────────────────────────────────────────────────
//
// Главный вход для японских открытых данных: английского названия там
// часто нет вовсе (у Осаки колонка объявлена и пуста во всех 2012 строках),
// а иероглифы читать нечем — чтения топонимов нерегулярны.
const k = (kana, expected) => check(`кана «${kana}»`, kanaToCyrillic(kana).value, expected)

k('クマノ', 'кумано')
k('シブヤ', 'сибуя')            // シ = си, не «ши»
k('ハチマングウ', 'хатимангу')
k('ツルガオカ', 'цуругаока')
k('カナザワ', 'канадзава')      // ザ = дза
k('ホッカイドウ', 'хоккайдо')    // ッ — удвоение, ドウ — долгота
k('くまの', 'кумано')          // хирагана читается так же, как катакана

// Долгота: знак ー и вторая гласная дают одно и то же.
k('トーキョー', 'токё')
k('トウキョウ', 'токё')
// Смотреть надо на ЗВУК, а не на букву: «ジョ» это «дзё» с о-образным
// гласным, «キュ» — «кю» с у-образным. Первая версия сравнивала буквально
// и давала «Эндзёудзи» вместо «Эндзёдзи», «Кюусо» вместо «Кюсо».
k('エンジョウジ', 'эндзёдзи')
k('キュウソ', 'кюсо')

// ん перед йотированной — твёрдый знак.
k('ホンヤ', 'хонъя')

// Дифтонги — те же правила и те же измеренные основания, что в ромадзи.
k('ヌサマイ', 'нусамай')        // ай
k('メイジ', 'мэйдзи')          // эй
k('オイシ', 'оиси')            // ои, не «ойси»

// ── Имя из иероглифов и чтения ──────────────────────────────────────────
//
// Род объекта определяется по ИЕРОГЛИФАМ: 寺 это храм всегда, а «дзи»
// в конце чтения может оказаться частью обычного слова (平地 → «хэйдзи»).
const kn = (ja, kana, expected) => check(`«${ja}»`, poiNameFromKana(ja, kana).nameRu, expected)

kn('東大寺', 'トウダイジ', 'Храм Тодайдзи')
kn('熊野神社', 'クマノジンジャ', 'Святилище Кумано')
kn('伏見稲荷大社', 'フシミイナリタイシャ', 'Святилище Фусимиинари')
kn('浜詰温泉', 'ハマヅメオンセン', 'Горячие источники Хамадзумэ')
kn('大野城址', 'オオノジョウシ', 'Руины замка Оно')
kn('経ヶ岬', 'キョウガミサキ', 'Мыс Кёга')
// 山 читается и «сан», и «яма». Снимается только «сан»: «Гора Такао»,
// но «Арасияма» — название местности и остаётся целиком.
kn('磯砂山', 'イサナゴサン', 'Гора Исанаго')
kn('嵐山', 'アラシヤマ', 'Гора Арасияма')
// «-дзи», «-ин» остаются в имени: в базе «Кинкакудзи», не «Кинкаку».
kn('金閣寺', 'キンカクジ', 'Храм Кинкакудзи')
kn('三千院', 'サンゼンイン', 'Храм Сандзэнин')

// Кана не размечает границы слов — длинное название сливается в одно
// нечитаемое. Это не сбой разбора, а признак, что объект не POI.
{
  const r = poiNameFromKana('夕日ヶ浦温泉　佳松苑はなれ風香', 'ユウヒガウラオンセンカショウエンハナレフウカ')
  check('бегущее слово помечено', r.warnings.some((w) => /букв слитно/.test(w)), true)
}

if (failures.length) {
  console.error(`\n✗ провалено ${failures.length} из ${passed + failures.length}\n`)
  for (const f of failures) console.error(`  ${f}\n`)
  process.exitCode = 1
} else {
  console.log(`✓ Поливанов: ${passed} проверок пройдено`)
}
