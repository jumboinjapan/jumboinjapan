#!/bin/bash
# Отправить в GitHub то, что уже закоммичено. Одна команда — чтобы с телефона
# печатать три символа, а не три строки.
#
#   jj          — показать неотправленное и отправить
#   jj "текст"  — сначала закоммитить ОТСЛЕЖИВАЕМЫЕ изменённые файлы, потом отправить
#
# Новые файлы (untracked) скрипт не добавляет НАМЕРЕННО. `git add -A` с телефона —
# это способ однажды отправить в общий репозиторий незаконченную работу и ключи
# из случайно оказавшегося рядом файла. Новое добавляйте руками, глядя в экран.
set -e
cd "$(dirname "$0")/.."

# Замки оставляет мост Cowork: переименовывать файлы он умеет, удалять — нет,
# поэтому после прогонов агента их скапливается пачка.
rm -f .git/*.lock .git/*.lock.stale* 2>/dev/null || true

if [ -n "$1" ]; then
  git add -u
  git commit -m "$1"
fi

echo "── к отправке ──"
git log --oneline @{u}..HEAD || true
echo "── не закоммичено ──"
git status --short
echo "───────────────"
git push
