/**
 * ВРЕМЕННЫЙ мост совместимости со старым полем `POI Category (RU)` в Airtable.
 *
 * УСЛОВИЕ УДАЛЕНИЯ: файл убирается вместе с его потребителями, когда старые
 * записи и пути совместимости больше не нуждаются в POI Category (RU).
 * Канонические поля уже содержат коды; мост заполняет только точную проекцию
 * в старое поле и помогает читать сохранившиеся старые категории.
 *
 * Чем этот модуль НЕ является:
 *   • не источник классификации — решение принимают правила и модель через
 *     classification-contract.mjs, а маршрут вычисляет реестр;
 *   • не влияет на entityKind, poiPrimaryType, facets и resolveRoute;
 *   • не участвует в промпте, в схеме предложения и в новом результате.
 *
 * Путь записи использует мост только при подготовке полей Airtable.
 * src/lib/poi-category.ts читает те же точные соответствия в обратную сторону
 * для legacy-карточек; своего списка синонимов у интерфейса нет.
 * Мост не пишет в базу и не задаёт тип вместо классификатора.
 *
 * Главное правило: неоднозначное соответствие НЕ УГАДЫВАЕТСЯ. Там, где старое
 * значение шире или уже нового кода, мост возвращает null. Старое поле остаётся
 * пустым, канонический тип сохраняется, причина попадает в отчёт и Notes.
 * При обратном чтении такое старое значение требует уточнения по фактам.
 * Ближайшее слово вместо точного соответствия не выбирается.
 */

