/**
 * @param   {string|null} poiPrimaryType код типа из реестра
 * @returns {{ value: string|null, reason: string|null }}
 *          value — старое русское значение, если перевод точен;
 *          reason — почему перевода нет, если value === null.
 */
export function legacyAirtableCategory(poiPrimaryType) {
  if (typeof poiPrimaryType !== 'string' || !poiPrimaryType) {
    return { value: null, reason: 'тип объекта не определён' }
  }
  const exact = EXACT[poiPrimaryType]
  if (exact) return { value: exact, reason: null }
  const known = UNREPRESENTABLE[poiPrimaryType]
  if (known) return { value: null, reason: known }
  return { value: null, reason: `код ${poiPrimaryType} появился в реестре после этого моста` }
}

/** Коды с точным переводом — для тестов и отчётов, не для выбора типа. */
export const REPRESENTABLE_CODES = Object.freeze(Object.keys(EXACT))

/** Коды, которые старое поле выразить не может, с причиной. */
export const UNREPRESENTABLE_CODES = Object.freeze({ ...UNREPRESENTABLE })
